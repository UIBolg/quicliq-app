#!/usr/bin/env node
/**
 * Turns the SVGs exported from Figma ("Icons & Illustrations", node 79:2) into React Native code.
 *   assets/icons/*.svg          -> src/assets/icons.generated.ts
 *   assets/illustrations/*.svg  -> src/assets/illustrations.generated.ts
 *   assets/flags/*.svg          -> src/assets/flags.generated.ts
 * Each file exports a map { name: svgXmlString } rendered with react-native-svg's <SvgXml>
 * (works on iOS, Android and web without a Metro SVG transformer).
 * Icon strokes/fills of Neutral/Ink are replaced by "currentColor" so icons can be recoloured.
 */
const fs = require('fs');
const path = require('path');
const root = path.resolve(__dirname, '..');

function build(srcDir, outFile, exportName, recolour) {
  const dir = path.join(root, srcDir);
  const files = fs.existsSync(dir) ? fs.readdirSync(dir).filter((f) => f.endsWith('.svg')).sort() : [];
  const entries = files.map((f) => {
    let xml = fs.readFileSync(path.join(dir, f), 'utf8').replace(/\s+/g, ' ').trim();
    if (recolour) xml = xml.replace(/(stroke|fill)="#(171717|000000|000)"/gi, '$1="currentColor"');
    return `  ${JSON.stringify(f.replace(/\.svg$/, ''))}: ${JSON.stringify(xml)},`;
  });
  fs.mkdirSync(path.dirname(path.join(root, outFile)), { recursive: true });
  fs.writeFileSync(
    path.join(root, outFile),
    `// AUTO-GENERATED by scripts/svg-to-components.js from ${srcDir} — do not edit.\n` +
      `export const ${exportName}: Record<string, string> = {\n${entries.join('\n')}\n};\n`,
  );
  console.log(`[svg] ${srcDir}: ${files.length} files -> ${outFile}`);
}

build('assets/icons', 'src/assets/icons.generated.ts', 'iconXml', true);
build('assets/illustrations', 'src/assets/illustrations.generated.ts', 'illustrationXml', false);
build('assets/flags', 'src/assets/flags.generated.ts', 'flagXml', false);
// Logo 32:256: assets/logo/brand.svg (Tone=Brand), assets/logo/white.svg (Tone=White)
build('assets/logo', 'src/assets/logo.generated.ts', 'logoXml', false);
