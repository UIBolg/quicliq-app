#!/usr/bin/env node
/**
 * Scans assets/fonts and generates src/theme/fontFiles.generated.ts, mapping each Quicliq font face
 * (see src/theme/fonts.ts) to the matching file. Run automatically before start/web/ios/android.
 *
 * Matching is by keywords in the file name (case-insensitive, .ttf/.otf):
 *   Avenir + Roman|Book|Regular -> Avenir-Roman     Avenir + Medium -> Avenir-Medium
 *   Avenir + Heavy              -> Avenir-Heavy     Avenir + Black  -> Avenir-Black
 *   Frutiger/Arabic + 45|Light  -> FrutigerLTArabic-45Light
 *   Frutiger/Arabic + 55|Roman|Regular -> FrutigerLTArabic-55Roman
 *   Frutiger/Arabic + 65|Bold   -> FrutigerLTArabic-65Bold
 *   Frutiger/Arabic + 75|Black  -> FrutigerLTArabic-75Black
 * Exact file names like "Avenir-Heavy.ttf" always work.
 */
const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const dir = path.join(root, 'assets/fonts');
const out = path.join(root, 'src/theme/fontFiles.generated.ts');

const rules = [
  ['Avenir-Roman', /avenir/i, /(roman|book|regular)/i],
  ['Avenir-Medium', /avenir/i, /medium/i],
  ['Avenir-Heavy', /avenir/i, /heavy/i],
  ['Avenir-Black', /avenir/i, /black/i],
  ['FrutigerLTArabic-45Light', /(frutiger|arabic)/i, /(45|light)/i],
  ['FrutigerLTArabic-55Roman', /(frutiger|arabic)/i, /(55|roman|regular)/i],
  ['FrutigerLTArabic-65Bold', /(frutiger|arabic)/i, /(65|bold)/i],
  ['FrutigerLTArabic-75Black', /(frutiger|arabic)/i, /(75|black)/i],
];

const files = fs.existsSync(dir) ? fs.readdirSync(dir).filter((f) => /\.(ttf|otf)$/i.test(f)) : [];
const found = {};
for (const [face, fam, cut] of rules) {
  const exact = files.find((f) => f.replace(/\.(ttf|otf)$/i, '').toLowerCase() === face.toLowerCase());
  const match = exact || files.find((f) => fam.test(f) && cut.test(f) && !Object.values(found).includes(f));
  if (match) found[face] = match;
}

const lines = Object.entries(found).map(
  ([face, file]) => `  '${face}': require('../../assets/fonts/${file}'),`,
);
fs.writeFileSync(
  out,
  `// AUTO-GENERATED by scripts/register-fonts.js — do not edit.\n` +
    `// Faces found in assets/fonts: ${Object.keys(found).length}/${rules.length}\n` +
    `export const fontFiles: Record<string, number> = {\n${lines.join('\n')}\n};\n`,
);
const missing = rules.map((r) => r[0]).filter((f) => !found[f]);
console.log(`[fonts] registered ${Object.keys(found).length}/${rules.length} faces` +
  (missing.length ? ` — missing (system fallback): ${missing.join(', ')}` : ''));
